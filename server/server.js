const jobs = new Map();
const JOB_TTL_MS = 30 * 60 * 1000;

function newJob() {
  const id = crypto.randomBytes(8).toString('hex');
  const job = {
    id, state: 'queued', progress: 0, stage: 'queued', error: null,
    createdAt: Date.now(), result: null,
  };
  jobs.set(id, job);
  return job;
}

// Housekeeping: drop old jobs.
setInterval(() => {
  const now = Date.now();
  for (const [id, j] of jobs) if (now - j.createdAt > JOB_TTL_MS) jobs.delete(id);
}, 60 * 1000).unref();

async function runInversionJob(job, req) {
  try {
    job.state = 'running';
    const clip = getAnyClip(req.clipId);
    const obs = clip.obs;
    const obsW = GEOM.obsW, obsH = GEOM.obsH;

    job.stage = 'estimating noise'; job.progress = 0.05;
    const noiseEst = estimateNoise(obs[0], obsW, obsH);
    const autoLam = autoLambda(noiseEst);

    const assumption = {
      id: 'user',
      label: 'user assumption',
      kind: req.kind ?? 'linear',
      vx: req.vx ?? 0, vy: req.vy ?? 0,
      amp: req.amp ?? 0, freq: req.freq ?? 0,
      omega: req.omega ?? 0, pivotX: req.pivotX ?? 0, pivotY: req.pivotY ?? 0,
      rho: req.rho ?? 0.8,
      exposureKind: req.exposureKind ?? 'uniform',
      refIndex: req.refIndex ?? clip.refIndex,
      lambda: req.lambda ?? autoLam,
      lambdaMode: req.lambdaMode ?? 'auto',
      tv: req.tv ?? 0,
      maxIter: req.maxIter ?? 50,
    };
    if (assumption.lambdaMode === 'auto') assumption.lambda = autoLam;

    job.stage = 'building exposure operators'; job.progress = 0.15;
    await tick();

    job.stage = 'conjugate-gradient solve'; job.progress = 0.3;
    const main = invert(obs, assumption, {});
    job.progress = 0.7;

    // Sequential hypotheses comparison requested by the UI.
    let comparison = null;
    if (req.compare) {
      job.stage = 'comparing motion hypotheses'; job.progress = 0.75;
      await tick();
      const angle = Math.atan2(assumption.vy, assumption.vx);
      const speed = Math.hypot(assumption.vx, assumption.vy);
      const hyps = [
        { ...assumption, id: 'assumed', label: 'assumed (forward)' },
        { ...assumption, id: 'reversed', label: 'reversed direction', vx: -assumption.vx, vy: -assumption.vy },
        { ...assumption, id: 'stationary', label: 'stationary', vx: 0, vy: 0 },
      ];
      if (speed > 0) {
        hyps.push({
          ...assumption, id: 'slower', label: '0.6x speed',
          vx: 0.6 * speed * Math.cos(angle), vy: 0.6 * speed * Math.sin(angle),
        });
      }
      comparison = compareHypotheses(obs, hyps, {});
      comparison.results = comparison.results.map((r) => ({
        id: r.id, label: r.label, forwardRmse: r.forwardRmse,
        estimateImage: grayPNG(r.estimate, obsW, obsH),
      }));
      comparison.scored = comparison.scored.map((s) => ({ id: s.id, label: s.label, forwardRmse: s.forwardRmse }));
      // Keep a compact per-hypothesis forward residual history for the note.
      comparison.lambdaUsed = assumption.lambda;
    }

    job.stage = 'evaluating forward model'; job.progress = 0.85;
    const evidence = evidenceFor(clip, main);
    job.progress = 0.95;

    job.result = {
      clipId: req.clipId,
      assumption,
      noiseEstimate: noiseEst,
      autoLambda: autoLam,
      estimate: arrayToDisplay(main.estimate),
      support: arrayToDisplay(main.support ?? new Float64Array(obsW * obsH)),
      reblur: main.reblur.map((r) => ({ predicted: arrayToDisplay(r.predicted), residual: arrayToDisplay(r.residual) })),
      residualStats: residualStats(main.reblur, obsW, obsH),
      history: main.history,
      iterations: main.iterations,
      finalRelResidual: main.finalRelResidual,
      kernel: kernelsForUI(main.kernel),
      evidence,
      comparison,
      widths: { w: obsW, h: obsH },
    };
    job.state = 'done';
    job.progress = 1;
    job.stage = 'done';
  } catch (err) {
    job.state = 'failed';
    job.error = err && err.stack ? err.stack.split('\n').slice(0, 6).join('\n') : String(err);
    console.error('job failed', err);
  }
}

function tick() {
  return new Promise((r) => setImmediate(r));
}

// ---------------------------------------------------------------------------
// Layered inversion job. This calls the REAL layered kernel in src/layers.js:
// a joint stacked normal-equation solve over per-layer latents, data-driven
// coverage masks by default, and a closed-loop re-blur residual. Nothing here
// is hard-coded; every image returned is produced by the solver.
// ---------------------------------------------------------------------------

async function runLayeredJob(job, req) {
  try {
    job.state = 'running';
    const clip = getLayeredClip(req.clipId);
    const { obsW, obsH } = GEOM;

    // Optional blur-segment (frame range). Defaults to the whole clip.
    const total = clip.obs.length;
    const start = Math.max(0, Math.min(total - 1, req.frameStart ?? 0));
    const end = Math.max(start + 1, Math.min(total, (req.frameEnd ?? total - 1) + 1));
    const obs = clip.obs.slice(start, end);
    // refIndex is local to the slice.
    const refIndex = Math.min(obs.length - 1, Math.max(0, (req.refIndex ?? clip.refIndex) - start));

    const estimateMasks = req.estimateMasks !== false;
    const maxLayers = MAX_LAYERS;
    const nLayer = Math.max(1, Math.min(maxLayers, req.layerCount ?? 2));
    const rho = req.rho ?? clip.spec.rho;
    const exposureKind = req.exposureKind ?? clip.spec.exposureKind ?? 'uniform';
    const lambda = req.lambda ?? 0.01;
    const maxIter = req.maxIter ?? 35;

    // Velocity seeds. They are starting guesses only; with alternations > 0 the
    // kernel re-estimates each layer's velocity by a protected residual scan.
    const layers = [];
    for (let l = 0; l < nLayer; l++) {
      const seed = req.layerSeeds?.[l] ?? {};
      layers.push({
        kind: 'linear',
        vx: seed.vx ?? (l === 0 ? req.bgVx ?? 0 : req.fgVx ?? 0),
        vy: seed.vy ?? (l === 0 ? req.bgVy ?? 0 : req.fgVy ?? 0),
      });
    }

    const spec = {
      layers,
      refIndex, rho, exposureKind, lambda, maxIter,
      alternations: req.alternations ?? 0,
      estimateMasks,
      bgVelocity: { x: layers[0].vx, y: layers[0].vy },
    };

    job.stage = estimateMasks ? 'estimating data-driven layer lock regions' : 'building layer operators';
    job.progress = 0.1;
    await tick();
    job.stage = 'joint layered conjugate-gradient solve';
    job.progress = 0.35;

    // Single-motion baseline (the global-model special configuration) so the UI
    // can show the layered-vs-single forward-residual comparison.
    const single = invertSingleLayer(obs, {
      vx: layers[0].vx, vy: layers[0].vy, refIndex, rho, exposureKind, lambda, maxIter,
    });
    job.progress = 0.55;
    await tick();

    // The requested parameterisation strategy. Both strategies are scored by the
    // SAME forward residual when the user asks for the comparison.
    let main;
    let strategy = null;
    if (req.compareStrategies) {
      job.stage = 'comparing independent vs shared-background strategies';
      const cmp = compareLayeredStrategies(obs, spec);
      main = cmp.results[cmp.selected];
      strategy = {
        selected: cmp.selected,
        margin: cmp.margin,
        scores: cmp.scores,
      };
    } else {
      main = invertLayered(obs, spec);
    }
    job.progress = 0.85;
    await tick();

    const forwardRmse = layeredResidualRmse(main, obs);
    const singleRmse = layeredResidualRmse(single, obs);

    job.stage = 'serializing layered estimate and re-blur residual';
    job.progress = 0.95;
    const result = serializeLayered(main, obs, {
      clipId: req.clipId, frameStart: start, frameEnd: end - 1, refIndex,
      estimateMasks, forwardRmse, singleRmse, single, strategy, rho, exposureKind,
    });
    job.result = result;
    job.state = 'done';
    job.progress = 1;
    job.stage = 'done';
  } catch (err) {
    job.state = 'failed';
    job.error = err && err.stack ? err.stack.split('\n').slice(0, 6).join('\n') : String(err);
    console.error('layered job failed', err);
  }
}

function grayArray(img) { return Array.from(img, (v) => Math.round(Math.max(0, Math.min(1, v)) * 1000) / 1000); }

function serializeLayered(result, obs, meta) {
  const { obsW, obsH } = GEOM;
  const reblur = result.reblur.map((r) => ({
    predicted: grayArray(r.predicted),
    residual: grayArray(r.residual),
  }));
  const residualCombined = combinedResidualRGB(
    reblur.map((r) => ({ residual: Float64Array.from(r.residual) })),
    0.005,
  );
  const layerCount = result.layers.length;
  return {
    mode: 'layered',
    clipId: meta.clipId,
    frameStart: meta.frameStart,
    frameEnd: meta.frameEnd,
    refIndex: meta.refIndex,
    estimateMasks: meta.estimateMasks,
    strategy: result.strategy,
    strategyChoice: meta.strategy,
    layerCount,
    maxLayers: MAX_LAYERS,
    forwardRmse: meta.forwardRmse,
    singleMotionRmse: meta.singleRmse,
    residualImprovement: meta.singleRmse > 0 ? (meta.singleRmse - meta.forwardRmse) / meta.singleRmse : 0,
    iterations: result.iterations,
    velocityLog: result.velocityLog,
    // Per-layer exposure kernels (the independent per-layer trajectories).
    kernels: result.kernels.map(kernelsForUI),
    // Composite + per-layer recovered images and their coverage/uncertainty.
    estimate: grayArray(result.estimate),
    layerEstimates: result.layerEstimates.map(grayArray),
    layerMasks: result.layerMasks.map(grayArray),
    uncertainty: result.uncertainty.map(grayArray),
    coverage: result.coverage.map(grayArray),
    layerVelocities: result.layers.map((l) => ({ vx: l.vx ?? 0, vy: l.vy ?? 0, fixedCoverage: !!l.fixedCoverage })),
    reblur,
    // Single-motion special configuration, for the side-by-side comparison.
    singleMotion: {
      estimate: grayArray(meta.single.estimate),
      forwardRmse: meta.singleRmse,
    },
    widths: { w: obsW, h: obsH },
    images: {
      estimate: grayPNG(Float64Array.from(result.estimate), obsW, obsH),
      refObs: grayPNG(obs[meta.refIndex], obsW, obsH),
      predictedRef: grayPNG(Float64Array.from(result.reblur[meta.refIndex].predicted), obsW, obsH),
      residualCombined: colorPNG(residualCombined.rgb, obsW, obsH),
      layerEstimates: result.layerEstimates.map((a) => grayPNG(Float64Array.from(a), obsW, obsH)),
      layerMasks: result.layerMasks.map((a) => grayPNG(Float64Array.from(a), obsW, obsH)),
      uncertainty: result.uncertainty.map((a) => grayPNG(Float64Array.from(a), obsW, obsH)),
      singleEstimate: grayPNG(Float64Array.from(meta.single.estimate), obsW, obsH),
    },
  };
}

// Evidence block: computed with truth available (server-side only), clearly
// labelled in the UI as "synthetic ground truth, evaluation only".
function evidenceFor(clip, result) {
  const ev = evaluate(result.estimate, clip.refSharp, result.reblur, clip.obs, {});
  return {
    psnr: ev.psnr,
    ssim: ev.ssim,
    blurPsnr: ev.blurPsnr,
    gainDb: ev.gainDb,
    forwardRmse: ev.forwardRmse,
    forwardToNoise: ev.forwardToNoise,
    noiseSigmaEstimate: ev.noiseSigmaEstimate,
    ringing: ev.ringing,
    regions: ev.regions,
    note: 'Ground truth is synthetic and used only for scoring; the solver above never receives it.',
  };
}

