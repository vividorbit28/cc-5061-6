const LAYERED_CLIPS = new Map();
for (const c of LAYERED_CATALOG) LAYERED_CLIPS.set(c.id, { id: c.id, spec: c.opts, title: c.title });
const layeredCache = new Map();
function getLayeredClip(id) {
  if (!LAYERED_CLIPS.has(id)) throw new Error(`unknown layered clip ${id}`);
  if (!layeredCache.has(id)) layeredCache.set(id, makeLayeredClip(LAYERED_CLIPS.get(id).spec));
  return layeredCache.get(id);
}
function isLayeredId(id) { return LAYERED_CLIPS.has(id); }

// Normalised accessor so the single-motion path can also read layered clips:
// expose obs/refIndex plus a refSharp alias onto the layered clean reference.
function getAnyClip(id) {
  if (isLayeredId(id)) {
    const lc = getLayeredClip(id);
    return {
      obs: lc.obs,
      refIndex: lc.refIndex,
      refSharp: lc.clean[lc.refIndex],
      clean: lc.clean,
      spec: lc.spec,
    };
  }
  return getClip(id);
}

const clipCache = new Map();
function getClip(id) {
  if (!CLIPS.has(id)) throw new Error(`unknown clip ${id}`);
  if (!clipCache.has(id)) {
    const entry = CLIPS.get(id);
    clipCache.set(id, makeClip(entry.spec));
  }
  return clipCache.get(id);
}

function truthOf(id) {
  const clip = getClip(id);
  return { latent: clip.latent, scene: clip.scene };
}

